package com.aidentx.core.notifications_management.enums;

/**
 * Enumeration representing different types of notifications in the system.
 *
 * @author aidentx Development Team
 * @version 1.0
 * @since 2025-08-18
 */
public enum NotificationType {
    
    /**
     * General notifications for user activities and system events.
     */
    NOTIFICATIONS,
    
    /**
     * Important announcements from administrators or system-wide communications.
     */
    ANNOUNCEMENTS,
    
    /**
     * Critical alerts requiring immediate user attention.
     */
    ALERTS
}
