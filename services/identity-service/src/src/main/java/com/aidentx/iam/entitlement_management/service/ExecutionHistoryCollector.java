package com.aidentx.iam.entitlement_management.service;

import com.aidentx.iam.entitlement_management.model.entity.RuleExecutionDetail;
import com.aidentx.iam.entitlement_management.model.entity.RuleExecutionHistory;

import java.time.Instant;
import java.util.*;

/**
 * In-memory collector for execution history data during rule evaluation.
 *
 * <p>Created at the start of each rule evaluation, populated during processing,
 * and flushed to the database after evaluation completes (success or failure).
 *
 * <p>This is NOT a Spring bean. A new instance is created per evaluation run
 * to avoid thread-safety issues. The evaluation engine creates it, passes it
 * through the processing pipeline, and calls {@link ExecutionHistoryWriter#flush}
 * at the end.
 *
 * <p>Only actionable outcomes are recorded (ASSIGNED, SKIPPED_NO_SHADOW,
 * REVOKED, ERROR). ALREADY_ASSIGNED is counted but not detailed (lazy capture).
 *
 * <p><b>Important:</b> The collector does NOT set the ID on the history entity.
 * The ID is generated by Hibernate on persist. The {@code executionId} tracked
 * here is a correlation ID used to link detail records to their parent history
 * record — it is set AFTER the history record is persisted in
 * {@link ExecutionHistoryWriter#flush}.
 */
public class ExecutionHistoryCollector {

    private final String tenantId;
    private final UUID ruleId;
    private final String ruleName;
    private final UUID entitlementId;
    private final String entitlementDisplayName;
    private final UUID resourceId;
    private final RuleExecutionHistory.TriggerType triggerType;
    private final String triggeredBy;
    private final List<Map<String, Object>> conditionsSnapshot;
    private final List<String> identityTypes;
    private final long startedAt;

    /**
     * Set AFTER the history record is persisted. Used as FK on detail records.
     */
    private UUID executionId;

    private int identitiesMatched = 0;
    private int assignmentsCreated = 0;
    private int assignmentsRevoked = 0;
    private int skippedNoShadow = 0;
    private int skippedAlreadyAssigned = 0;
    private int errorCount = 0;

    private final List<DetailRecord> pendingDetails = new ArrayList<>();

    public ExecutionHistoryCollector(
            String tenantId, UUID ruleId, String ruleName,
            UUID entitlementId, String entitlementDisplayName, UUID resourceId,
            RuleExecutionHistory.TriggerType triggerType, String triggeredBy,
            List<Map<String, Object>> conditionsSnapshot, List<String> identityTypes) {
        this.tenantId = tenantId;
        this.ruleId = ruleId;
        this.ruleName = ruleName;
        this.entitlementId = entitlementId;
        this.entitlementDisplayName = entitlementDisplayName;
        this.resourceId = resourceId;
        this.triggerType = triggerType;
        this.triggeredBy = triggeredBy;
        this.conditionsSnapshot = conditionsSnapshot;
        this.identityTypes = identityTypes;
        this.startedAt = Instant.now().toEpochMilli();
    }

    // ===================================================================
    //  Recording methods — called during evaluation
    // ===================================================================

    /**
     * Sets the total number of identities that matched the rule conditions.
     *
     * @param count the matched count
     */
    public void setIdentitiesMatched(int count) {
        this.identitiesMatched = count;
    }

    /**
     * Records a new assignment being created for an identity.
     *
     * @param identityId  the identity UUID
     * @param displayName the identity's display name (snapshot)
     * @param shadowId    the shadow UUID used for the assignment
     * @param evidence    the match evidence JSON
     */
    public void recordAssigned(UUID identityId, String displayName,
                                UUID shadowId, Map<String, Object> evidence) {
        assignmentsCreated++;
        pendingDetails.add(new DetailRecord(
                identityId, displayName, RuleExecutionDetail.Outcome.ASSIGNED,
                shadowId, evidence, null));
    }

    /**
     * Records an identity that matched but had no shadow on the target resource.
     *
     * @param identityId  the identity UUID
     * @param displayName the identity's display name (snapshot)
     * @param evidence    the match evidence JSON
     */
    public void recordSkippedNoShadow(UUID identityId, String displayName,
                                       Map<String, Object> evidence) {
        skippedNoShadow++;
        pendingDetails.add(new DetailRecord(
                identityId, displayName, RuleExecutionDetail.Outcome.SKIPPED_NO_SHADOW,
                null, evidence, null));
    }

    /**
     * Records an identity that already had the assignment (no-op).
     * Only increments the counter — no detail record created (lazy capture).
     */
    public void recordAlreadyAssigned() {
        skippedAlreadyAssigned++;
    }

    /**
     * Records a revoked assignment (identity no longer matches conditions).
     *
     * @param identityId  the identity UUID
     * @param displayName the identity's display name
     * @param shadowId    the shadow UUID whose assignment was revoked
     */
    public void recordRevoked(UUID identityId, String displayName, UUID shadowId) {
        assignmentsRevoked++;
        Map<String, Object> evidence = new HashMap<>();
        evidence.put("reason", "Identity no longer matches rule conditions");
        pendingDetails.add(new DetailRecord(
                identityId, displayName, RuleExecutionDetail.Outcome.REVOKED,
                shadowId, evidence, null));
    }

    /**
     * Records an error processing a specific identity.
     *
     * @param identityId   the identity UUID
     * @param displayName  the identity's display name
     * @param errorMessage the error message
     */
    public void recordError(UUID identityId, String displayName, String errorMessage) {
        errorCount++;
        pendingDetails.add(new DetailRecord(
                identityId, displayName, RuleExecutionDetail.Outcome.ERROR,
                null, null, errorMessage));
    }

    /**
     * Adds revocation count from bulk revoke (no individual identity details available
     * because the native query doesn't return which specific identities were revoked).
     *
     * @param count the number of bulk revocations
     */
    public void addBulkRevocationCount(int count) {
        assignmentsRevoked += count;
    }

    // ===================================================================
    //  Build the final entities
    // ===================================================================

    /**
     * Builds the run-level history entity for a successful execution.
     *
     * <p><b>The ID is NOT set.</b> Hibernate will generate it on persist.
     * After persist, call {@link #setExecutionId} with the generated ID.
     *
     * @return the history entity (unsaved, no ID)
     */
    public RuleExecutionHistory buildSuccessHistory() {
        RuleExecutionHistory.ExecutionStatus status = errorCount > 0
                ? RuleExecutionHistory.ExecutionStatus.PARTIAL_FAILURE
                : RuleExecutionHistory.ExecutionStatus.SUCCESS;
        return buildHistory(status, null);
    }

    /**
     * Builds the run-level history entity for a failed execution.
     *
     * <p><b>The ID is NOT set.</b> Hibernate will generate it on persist.
     *
     * @param errorMessage the top-level error message
     * @return the history entity (unsaved, no ID)
     */
    public RuleExecutionHistory buildFailureHistory(String errorMessage) {
        return buildHistory(RuleExecutionHistory.ExecutionStatus.FAILURE, errorMessage);
    }

    private RuleExecutionHistory buildHistory(RuleExecutionHistory.ExecutionStatus status,
                                               String errorMessage) {
        long now = Instant.now().toEpochMilli();

        RuleExecutionHistory history = new RuleExecutionHistory();
        // DO NOT set ID — let Hibernate generate it
        history.setTenantId(tenantId);
        history.setRuleId(ruleId);
        history.setRuleName(ruleName);
        history.setEntitlementId(entitlementId);
        history.setEntitlementDisplayName(entitlementDisplayName);
        history.setResourceId(resourceId);
        history.setTriggerType(triggerType);
        history.setTriggeredBy(triggeredBy);
        history.setConditionsSnapshot(conditionsSnapshot);
        history.setIdentityTypes(identityTypes);
        history.setStatus(status);
        history.setIdentitiesMatched(identitiesMatched);
        history.setAssignmentsCreated(assignmentsCreated);
        history.setAssignmentsRevoked(assignmentsRevoked);
        history.setSkippedNoShadow(skippedNoShadow);
        history.setSkippedAlreadyAssigned(skippedAlreadyAssigned);
        history.setErrorCount(errorCount);
        history.setErrorMessage(errorMessage);
        history.setStartedAt(startedAt);
        history.setCompletedAt(now);
        history.setDurationMs(now - startedAt);
        return history;
    }

    /**
     * Builds the identity-level detail entities.
     *
     * <p><b>Must be called AFTER {@link #setExecutionId} is set.</b>
     * The executionId comes from the persisted history record's generated ID.
     *
     * @return list of detail entities ready for bulk save
     * @throws IllegalStateException if executionId has not been set
     */
    public List<RuleExecutionDetail> buildDetails() {
        if (executionId == null) {
            throw new IllegalStateException(
                    "executionId must be set before building details. "
                    + "Call setExecutionId() after persisting the history record.");
        }

        List<RuleExecutionDetail> details = new ArrayList<>(pendingDetails.size());
        for (DetailRecord pending : pendingDetails) {
            RuleExecutionDetail detail = new RuleExecutionDetail();
            // DO NOT set ID — let Hibernate generate it
            detail.setTenantId(tenantId);
            detail.setExecutionId(executionId);
            detail.setRuleId(ruleId);
            detail.setIdentityId(pending.identityId());
            detail.setIdentityDisplayName(pending.displayName());
            detail.setOutcome(pending.outcome());
            detail.setShadowId(pending.shadowId());
            detail.setMatchEvidence(pending.evidence());
            detail.setErrorMessage(pending.errorMessage());
            detail.setProcessedAt(Instant.now().toEpochMilli());
            details.add(detail);
        }
        return details;
    }

    // ===================================================================
    //  Accessors
    // ===================================================================

    /**
     * Sets the execution ID after the history record is persisted.
     * This ID is used as the FK on all detail records.
     *
     * @param executionId the Hibernate-generated UUID from the saved history record
     */
    public void setExecutionId(UUID executionId) {
        this.executionId = executionId;
    }

    /**
     * Returns the execution ID (null until history record is persisted).
     *
     * @return the execution ID or null
     */
    public UUID getExecutionId() {
        return executionId;
    }

    // ===================================================================
    //  Internal detail record
    // ===================================================================

    /**
     * Temporary in-memory holder for identity-level detail data.
     * Converted to {@link RuleExecutionDetail} entities in {@link #buildDetails()}.
     */
    private record DetailRecord(
            UUID identityId,
            String displayName,
            RuleExecutionDetail.Outcome outcome,
            UUID shadowId,
            Map<String, Object> evidence,
            String errorMessage
    ) {}
}