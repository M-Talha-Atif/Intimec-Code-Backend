package com.aidentx.auditlogdto;

import com.fasterxml.jackson.databind.JsonNode;

import java.time.Instant;
import java.util.UUID;

/**
 * Data Transfer Object representing an audit log event for Kafka transport.
 * <p>
 * This DTO is shared between producer and consumer microservices to ensure a consistent contract for audit log events.
 * It contains all relevant information about an action performed in the system, including actor, target, event type,
 * status, risk, timestamps, contextual details, state snapshots, metadata, error details, and governance data.
 * <p>
 * All fields are required for full audit traceability, and complex objects are serialized as JSON.
 *
 * @author aidentx
 * @since 1.0
 */
public class AuditLogKafkaEvent {
    /**
     * Constructs a new AuditLogKafkaEvent without an id (for cases where the id should be generated by the consumer/database).
     *
     * @param actorId      Unique identifier of the actor performing the action
     * @param actorType    Type of the actor (e.g., user, system)
     * @param actorName    Name of the actor (e.g., username, system name)
     * @param tenantId     Tenant identifier for multi-tenant support
     * @param objectId     Unique identifier of the target object
     * @param objectType   Type of the target object
     * @param event        Name or identifier of the event (e.g., LOGIN)
     * @param status       Status of the event (e.g., SUCCESS, FAILURE)
     * @param risk         Risk assessment (optional)
     * @param timestamp    When the event occurred
     * @param details      Contextual details (LogDetails as JSON)
     * @param stateBefore  State before the event (as JSON)
     * @param stateAfter   State after the event (as JSON)
     * @param metadata     Additional metadata (as JSON)
     * @param errorDetails Error details if the event failed
     * @param governance   Governance information (as JSON)
     * @param targetObject Target object information (as JSON)
     */
    public AuditLogKafkaEvent(UUID actorId, String actorType, String actorName, String tenantId, UUID objectId, String objectType, String event,
                             String status, String risk, Instant timestamp, JsonNode details, JsonNode stateBefore,
                             JsonNode stateAfter, JsonNode metadata, String errorDetails, JsonNode governance, JsonNode targetObject) {
        this.id = null;
        this.actorId = actorId;
        this.actorType = actorType;
        this.actorName = actorName;
        this.tenantId = tenantId;
        this.objectId = objectId;
        this.objectType = objectType;
        this.event = event;
        this.status = status;
        this.risk = risk;
        this.timestamp = timestamp;
        this.details = details;
        this.stateBefore = stateBefore;
        this.stateAfter = stateAfter;
        this.metadata = metadata;
        this.errorDetails = errorDetails;
        this.governance = governance;
        this.targetObject = targetObject;
    }
    /**
     * Unique identifier for the audit event. Can be null if the producer does not set it; the consumer/database may generate it.
     */
    private UUID id;
    private UUID actorId;
    private String actorType;
    private String actorName;
    private String tenantId;
    private UUID objectId;
    private String objectType;
    private String event;
    private String status;
    private String risk;
    private Instant timestamp;
    private JsonNode details;
    private JsonNode stateBefore;
    private JsonNode stateAfter;
    private JsonNode metadata;
    private String errorDetails;
    private JsonNode governance;
    /**
     * JSON structure representing the target object of the event (e.g., id, type, name, etc).
     */
    private JsonNode targetObject;

    /**
     * Default constructor.
     */
    public AuditLogKafkaEvent() {}

    /**
     * Constructs a new AuditLogKafkaEvent with all fields.
     *
     * @param id           Unique identifier for the audit event
     * @param actorId      Unique identifier of the actor performing the action
     * @param actorType    Type of the actor (e.g., user, system)
     * @param actorName    Name of the actor (e.g., username, system name)
     * @param tenantId     Tenant identifier for multi-tenant support
     * @param objectId     Unique identifier of the target object
     * @param objectType   Type of the target object
     * @param event        Name or identifier of the event (e.g., LOGIN)
     * @param status       Status of the event (e.g., SUCCESS, FAILURE)
     * @param risk         Risk assessment (optional)
     * @param timestamp    When the event occurred
     * @param details      Contextual details (LogDetails as JSON)
     * @param stateBefore  State before the event (as JSON)
     * @param stateAfter   State after the event (as JSON)
     * @param metadata     Additional metadata (as JSON)
     * @param errorDetails Error details if the event failed
     * @param governance   Governance information (as JSON)
     * @param targetObject Target object information (as JSON)
     */
    public AuditLogKafkaEvent(UUID id, UUID actorId, String actorType, String actorName, String tenantId, UUID objectId, String objectType, String event,
                             String status, String risk, Instant timestamp, JsonNode details, JsonNode stateBefore,
                             JsonNode stateAfter, JsonNode metadata, String errorDetails, JsonNode governance, JsonNode targetObject) {
        this.id = id;
        this.actorId = actorId;
        this.actorType = actorType;
        this.actorName = actorName;
        this.tenantId = tenantId;
        this.objectId = objectId;
        this.objectType = objectType;
        this.event = event;
        this.status = status;
        this.risk = risk;
        this.timestamp = timestamp;
        this.details = details;
        this.stateBefore = stateBefore;
        this.stateAfter = stateAfter;
        this.metadata = metadata;
        this.errorDetails = errorDetails;
        this.governance = governance;
        this.targetObject = targetObject;
    }

    public UUID getId() { return id; }
    public void setId(UUID id) { this.id = id; }
    public UUID getActorId() { return actorId; }
    public void setActorId(UUID actorId) { this.actorId = actorId; }
    public String getActorType() { return actorType; }
    public void setActorType(String actorType) { this.actorType = actorType; }
    public String getActorName() { return actorName; }
    public void setActorName(String actorName) { this.actorName = actorName; }
    public String getTenantId() { return tenantId; }
    public void setTenantId(String tenantId) { this.tenantId = tenantId; }
    public UUID getObjectId() { return objectId; }
    public void setObjectId(UUID objectId) { this.objectId = objectId; }
    public String getObjectType() { return objectType; }
    public void setObjectType(String objectType) { this.objectType = objectType; }
    public String getEvent() { return event; }
    public void setEvent(String event) { this.event = event; }
    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }
    public String getRisk() { return risk; }
    public void setRisk(String risk) { this.risk = risk; }
    public Instant getTimestamp() { return timestamp; }
    public void setTimestamp(Instant timestamp) { this.timestamp = timestamp; }
    public JsonNode getDetails() { return details; }
    public void setDetails(JsonNode details) { this.details = details; }
    public JsonNode getStateBefore() { return stateBefore; }
    public void setStateBefore(JsonNode stateBefore) { this.stateBefore = stateBefore; }
    public JsonNode getStateAfter() { return stateAfter; }
    public void setStateAfter(JsonNode stateAfter) { this.stateAfter = stateAfter; }
    public JsonNode getMetadata() { return metadata; }
    public void setMetadata(JsonNode metadata) { this.metadata = metadata; }
    public String getErrorDetails() { return errorDetails; }
    public void setErrorDetails(String errorDetails) { this.errorDetails = errorDetails; }
    public JsonNode getGovernance() { return governance; }
    public void setGovernance(JsonNode governance) { this.governance = governance; }
    public JsonNode getTargetObject() { return targetObject; }
    public void setTargetObject(JsonNode targetObject) { this.targetObject = targetObject; }
}
